#!/usr/bin/env python3
"""
tab02_parameters.py
Generate Table 2: Parameter registry with provenance tags [C], [A], [S].
Data source: paper9/params/params_master.yaml.
Outputs: paper9/tables/out/tab02_parameters.tex
"""
import os
import yaml

def _escape_text_mode(text: str) -> str:
    """Escape raw `_` and `^` that occur in text mode (outside `$...$`).

    Cells in this table are plain text with embedded math spans; a raw text-mode `_`/`^` is a
    LaTeX error ("Missing $ inserted"), so escape it. `\\_` and `\\textasciicircum{}` render the
    same characters the previous output attempted to print.
    """
    out, i, n, in_math = [], 0, len(text), False
    while i < n:
        ch = text[i]
        if ch == "\\" and i + 1 < n:                 # control sequence / escape pair: copy verbatim
            out.append(text[i:i + 2]); i += 2; continue
        if ch == "$":
            in_math = not in_math; out.append(ch); i += 1; continue
        if not in_math and ch == "_":
            out.append(r"\_"); i += 1; continue
        if not in_math and ch == "^":
            out.append(r"\textasciicircum{}"); i += 1; continue
        out.append(ch); i += 1
    return "".join(out)


def sanitize_latex(text: str) -> str:
    """Format mathematical formulas and escape text-mode specials in table text cells."""
    text = text.replace('invariant det(A^T A) = l_iso^4; l1=l_iso*sqrt(AR), l2=l_iso/sqrt(AR)',
                        r'invariant $\det(\mathbf{A}^\mathsf{T} \mathbf{A}) = l_{\mathrm{iso}}^4$; $l_1 = l_{\mathrm{iso}}\sqrt{\mathrm{AR}}, l_2 = l_{\mathrm{iso}}/\sqrt{\mathrm{AR}}$')
    text = text.replace('l1 = l_iso*sqrt(AR), l2 = l_iso/sqrt(AR)',
                        r'$l_1 = l_{\mathrm{iso}}\sqrt{\mathrm{AR}}, l_2 = l_{\mathrm{iso}}/\sqrt{\mathrm{AR}}$')
    text = text.replace('CALC_MASTER_PLAN', r'CALC\_MASTER\_PLAN')
    text = text.replace('&', r'\&')
    text = text.replace('%', r'\%')
    return _escape_text_mode(text)

def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
    params_file = os.path.join(repo_root, 'paper9/params/params_master.yaml')
    out_dir = os.path.join(repo_root, 'paper9/tables/out')
    os.makedirs(out_dir, exist_ok=True)
    out_tex = os.path.join(out_dir, 'tab02_parameters.tex')

    with open(params_file) as f:
        params = yaml.safe_load(f)['parameters']

    lines = [
        "% Auto-generated by tab02_parameters.py from params_master.yaml - DO NOT EDIT MANUALLY",
        "\\begin{tabularx}{\\textwidth}{@{}l l l c L{3.5cm} Y@{}}",
        "\\toprule",
        "Symbol & Value & Unit & Tag & Source / Baseline & Physical interpretation \\\\",
        "\\midrule"
    ]

    latex_syms = {
        'Lcell': '$L$',
        'lambda': '$\\lambda$',
        'mu': '$\\mu$',
        'rho': '$\\rho$',
        'ell2': '$\\ell_{\\mathrm{i}}^2$',
        'l_iso': '$l_{\\mathrm{iso}}$',
        'l1_aniso': '$l_1$',
        'l2_aniso': '$l_2$',
        'ar_scaling_rule': 'Scaling rule',
        'theta_sweep_deg': '$\\theta$',
        'ar_sweep': '$\\mathrm{AR}$',
        'N_seg': '$N_{\\mathrm{seg}}$',
        'N_kx_2d': '$N_{kx}$',
        'N_ky_2d': '$N_{ky}$',
        'N_bands_reported': '$N$',
        'tol_hermiticity': '$\\mathrm{tol}_{\\mathrm{Herm}}$',
        'tol_symmetry': '$\\mathrm{tol}_{\\mathrm{sym}}$',
        'eps_Delta': '$\\varepsilon_\\Delta$',
        'rho_matrix': '$\\rho_m$',
        'mu_matrix': '$\\mu_m$',
        'lambda_matrix': '$\\lambda_m$',
        'rho_inclusion': '$\\rho_i$',
        'mu_inclusion': '$\\mu_i$',
        'lambda_inclusion': '$\\lambda_i$',
        'r0_over_a': '$r_0/L$',
        'c_t_matrix': '$c_{t,m}$',
        'omega0_caseC': '$\\omega_{0,\\mathrm{C}}$',
        # P12A PCR6 additions (B1/B2/B3 benchmark rows)
        'b1_rho_A': '$\\rho_A$',
        'b1_c33_A': '$c_{33,A}$',
        'b1_a3_A': '$a_{3,A}$',
        'b1_rho_B': '$\\rho_B$',
        'b1_c33_B': "$c'_{33,B}$",
        'b1_a3_B': "$a'_{3,B}$",
        'b1_a_A': '$a_A$',
        'b1_a_B': '$a_B$',
        'b1_b_cell': '$b$',
        'b1_omega0': '$\\omega_0$',
        'b1_classical_limit': '$l{=}l_1{=}f{=}0$',
        'b2_l_caption': '$l$',
        'b2_l1_caption': '$l_1$',
        'b2_flexo_off': '$f, F$',
        'b2_L_ratio': '$L, L_1$',
        'b2_lbar_definition': '$\\bar{l}$',
        'b2_cfg_dim_micro': 'DIM-MICRO',
        'b2_cfg_dim_macro': 'DIM-MACRO',
        'b2_cfg_bar_macro': 'BAR-MACRO',
        'b3_mu_1': '$\\mu_1$',
        'b3_rho_1': '$\\rho_1$',
        'b3_a_1': '$a_1$',
        'b3_a_2': '$a_2$',
        'b3_mu_2': '$\\mu_2$',
        'b3_rho_2': '$\\rho_2$',
        'b3_omega0': '$\\omega_{0,\\mathrm{B3}}$',
        'b3_cbar_1': '$\\bar{c}_1$',
        'b3_dbar_1': '$\\bar{d}_1$',
        'b3_c_R': '$c_R$',
        'b3_d_R': '$d_R$',
    }

    for k, v in params.items():
        sym = latex_syms.get(k, k)
        val = v['value']
        if isinstance(val, str):
            val_str = r'\texttt{' + val.replace('_', r'\_') + '}'
        elif isinstance(val, list):
            if len(val) > 4:
                val_str = f"$\\{{{val[0]}, \\dots, {val[-1]}\\}}$"
            else:
                val_str = f"${val}$"
        elif isinstance(val, float) and abs(val) < 1e-4:
            val_str = f"${val:.2e}$"
        else:
            val_str = f"${val}$"

        unit = v['unit'].replace('^2', '$^2$').replace('^3', '$^3$')
        tag = v['tag']
        source = sanitize_latex(v['source'])
        desc = sanitize_latex(v['description'])

        lines.append(f"{sym} & {val_str} & {unit} & {tag} & {source} & {desc} \\\\")

    lines.extend([
        "\\bottomrule",
        "\\end{tabularx}"
    ])

    content = "\n".join(lines) + "\n"
    with open(out_tex, 'w') as f:
        f.write(content)
    print(f"Generated {out_tex}")

if __name__ == '__main__':
    main()
