#!/usr/bin/env python3
"""
tab04_consistency_suite.py
Generate Table 4: Eight-test internal consistency suite (Layer 5 verification).
Data sources: P4A (5a-5f) and P4B (5g-5h) verification suites.
Outputs: paper9/tables/out/tab04_consistency_suite.tex
"""
import os
import json

def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
    data_file = os.path.join(repo_root, 'paper9/verification/suite/p4b_5g_to_5i.json')
    out_dir = os.path.join(repo_root, 'paper9/tables/out')
    os.makedirs(out_dir, exist_ok=True)
    out_tex = os.path.join(out_dir, 'tab04_consistency_suite.tex')

    with open(data_file) as f:
        p4b_data = json.load(f)

    # 5g and 5h values from verified JSON
    err_5g = p4b_data['5g']['ellbar_gt0_rel']['200.0']
    err_5h_vg = p4b_data['5h']['max_rel_energy_vs_cd']
    err_5h_WT = p4b_data['5h']['max_W_minus_T']

    tests = [
        ("5a", "Hermiticity of $\\bar{\\mathbf{K}}, \\bar{\\mathbf{M}}$", "$\\|\\bar{\\mathbf{K}} - \\bar{\\mathbf{K}}^{\\mathsf{H}}\\| / \\|\\bar{\\mathbf{K}}\\| = 0$", "$2.01 \\times 10^{-16}$", "$< 10^{-12}$", "PASS"),
        ("5b", "Brillouin zone periodicity", "$\\omega(\\mathbf{k} + \\mathbf{G}) = \\omega(\\mathbf{k})$", "$9.66 \\times 10^{-16}$", "$< 10^{-10}$", "PASS"),
        ("5c", "Rotational invariance at $\\mathrm{AR}=1$", "$\\omega(\\theta) = \\omega(0)$", "$9.63 \\times 10^{-16}$", "$< 10^{-10}$", "PASS"),
        ("5d", "Long-wave acoustic branch slopes", "$v_T = c_T, v_L = c_L$", "$1.25 \\times 10^{-8}$", "$< 10^{-6}$", "PASS"),
        ("5e", "Diagonal rotation-swap symmetry", "$\\omega(\\theta+90^\\circ, l_1, l_2) = \\omega(\\theta, l_2, l_1)$", "$6.44 \\times 10^{-16}$", "$< 10^{-10}$", "PASS"),
        ("5f", "Matrix positive definiteness", "Two rigid modes at $\\Gamma$; interior $\\omega^2 > 0$", "$\\|\\omega_{\\Gamma, 1,2}\\| < 10^{-15}$", "Admissible", "PASS"),
        ("5g", "Micro-inertia high-$k$ phase velocity", "$\\bar{v}_p \\to v_{T,\\infty} = 0.3162$ as $\\bar{k} \\to \\infty$", f"${err_5g:.2e}$", "$< 10^{-3}$", "PASS"),
        ("5h", "Energy-flux / group-velocity identity", "$\\langle \\mathbf{S} \\rangle / (\\langle W \\rangle + \\langle T \\rangle) = \\nabla_{\\mathbf{k}} \\omega$", f"${err_5h_vg:.2e}$", "$< 10^{-6}$", "PASS"),
    ]

    lines = [
        "% Auto-generated by tab04_consistency_suite.py - DO NOT EDIT MANUALLY",
        "\\begin{tabularx}{\\textwidth}{@{}l L{4.5cm} l l l c@{}}",
        "\\toprule",
        "Test & Property & Expected identity & Observed error & Tolerance & Status \\\\",
        "\\midrule"
    ]

    for t in tests:
        lines.append(f"{t[0]} & {t[1]} & {t[2]} & {t[3]} & {t[4]} & \\textbf{{{t[5]}}} \\\\")

    lines.extend([
        "\\bottomrule",
        "\\end{tabularx}"
    ])

    content = "\n".join(lines) + "\n"
    with open(out_tex, 'w') as f:
        f.write(content)
    print(f"Generated {out_tex}")

if __name__ == '__main__':
    main()
