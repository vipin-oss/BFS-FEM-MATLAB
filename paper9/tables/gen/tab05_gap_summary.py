#!/usr/bin/env python3
"""
tab05_gap_summary.py
Generate Table 5: Gap summary, normalized gap width, and orientation sensitivity S_theta (Case H).
Data source: paper9/results/processed/table5_gap_summary.json.
Outputs: paper9/tables/out/tab05_gap_summary.tex
"""
import os
import json

def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
    data_file = os.path.join(repo_root, 'paper9/results/processed/table5_gap_summary.json')
    out_dir = os.path.join(repo_root, 'paper9/tables/out')
    os.makedirs(out_dir, exist_ok=True)
    out_tex = os.path.join(out_dir, 'tab05_gap_summary.tex')

    with open(data_file) as f:
        d = json.load(f)
        rows = d['rows']
        stheta = d['sensitivity_Stheta']

    # Select representative cases across AR and theta
    selected_ar = [1.0, 3.0, 5.0, 10.0]
    selected_th = [0.0, 45.0, 90.0]

    lines = [
        "% Auto-generated by tab05_gap_summary.py - DO NOT EDIT MANUALLY",
        "\\begin{tabularx}{\\textwidth}{@{}c c c r r r r c c@{}}",
        "\\toprule",
        "$\\mathrm{AR}$ & $\\theta$ & Bands & $\\Delta_{GX}$ & $\\Delta_{\\mathrm{path}}$ & $\\Delta_{\\mathrm{complete}}$ & $\\Delta/\\bar{\\omega}_{\\mathrm{mid}}$ & Gap class & $\\Delta[\\mathrm{leg}] \\ge \\Delta[\\mathrm{path}] \\ge \\Delta[\\mathrm{complete}]$ \\\\",
        "\\midrule"
    ]

    for r in rows:
        if r['AR'] in selected_ar and r['theta_deg'] in selected_th and r['band_pair'] == [2, 3]:
            ar_str = f"{int(r['AR'])}"
            th_str = f"{int(r['theta_deg'])}^\\circ"
            bands_str = f"{r['band_pair'][0]}--{r['band_pair'][1]}"
            dgx = f"{r['delta_GX']:+.4f}"
            dpath = f"{r['delta_path']:+.4f}"
            dcomp = f"{r['delta_complete']:+.4f}"
            norm_w = f"{r['norm_gap_width']:+.4f}"
            gtype = "Directional" if r['delta_GX'] > 0 else "None"
            ineq = "PASS" if r['inequality_holds'] else "FAIL"

            lines.append(f"${ar_str}$ & ${th_str}$ & {bands_str} & ${dgx}$ & ${dpath}$ & ${dcomp}$ & ${norm_w}$ & {gtype} & \\textbf{{{ineq}}} \\\\")

    lines.extend([
        "\\midrule",
        "\\multicolumn{9}{@{}l@{}}{\\textbf{Orientation sensitivity} $S_\\theta = \\max_\\theta |\\partial\\Delta/\\partial\\theta| / \\max_\\theta \\Delta$ [$\\mathrm{rad}^{-1}$]:} \\\\",
    ])

    stheta_parts = []
    for ar in [1.0, 2.0, 3.0, 5.0, 7.0, 10.0]:
        val = stheta[f'AR_{int(ar)}']['S_theta_rad_inv']
        stheta_parts.append(f"$\\mathrm{{AR}}={int(ar)}: {val:.3f}$")

    lines.append(f"\\multicolumn{{9}}{{@{{}}l@{{}}}}{{{', '.join(stheta_parts[:3])}}} \\\\")
    lines.append(f"\\multicolumn{{9}}{{@{{}}l@{{}}}}{{{', '.join(stheta_parts[3:])}}} \\\\")

    lines.extend([
        "\\bottomrule",
        "\\end{tabularx}"
    ])

    content = "\n".join(lines) + "\n"
    with open(out_tex, 'w') as f:
        f.write(content)
    print(f"Generated {out_tex}")

if __name__ == '__main__':
    main()
