#!/usr/bin/env python3
"""
tab06_convergence_floor.py
Generate Table 6: Mesh convergence, observed convergence rate (95 % CI), measurement-resolution
admissibility (Rule R-fit, Blueprint v1.4 section 5.7) and the operational resolution floor.
Data sources:
  * paper9/verification/suite/p4b_5g_to_5i.json                (governing Test 5i result; numerical baseline)
  * paper9/audit/evidence/p12h/rule_rfit_governing.json        (per-level reproducibility s_i and rule constants)
Outputs: paper9/tables/out/tab06_convergence_floor.tex
"""
import os
import json

def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
    data_file = os.path.join(repo_root, 'paper9/verification/suite/p4b_5g_to_5i.json')
    out_dir = os.path.join(repo_root, 'paper9/tables/out')
    os.makedirs(out_dir, exist_ok=True)
    out_tex = os.path.join(out_dir, 'tab06_convergence_floor.tex')

    with open(data_file) as f:
        data = json.load(f)['5i']

    # Rule R-fit inputs (Blueprint v1.4 §5.7): per-level reproducibility s_i, frozen constants.
    rule_file = os.path.join(repo_root, 'paper9/audit/evidence/p12h/rule_rfit_governing.json')
    with open(rule_file) as f:
        rule = json.load(f)
    F = rule['rule']['F']
    spread_floor = rule['rule']['spread_floor']
    spreads = rule['reproducibility_inputs']['governing_era']['spreads']

    meshes = data['meshes'] # [4, 8, 16, 32]
    omegas = data['omega']
    rel_errs = data['rel_err']
    slope = data['slope']
    ci = data['CI95']
    eps_Delta = data['eps_Delta']
    om_exact = data['omega_exact']

    lines = [
        "% Auto-generated by tab06_convergence_floor.py - DO NOT EDIT MANUALLY",
        "% Rate fitted over the levels admissible under Rule R-fit (Blueprint v1.4 section 5.7):",
        "%   level included <=> relative error > F * max(reproducibility, 1e-15), F = 3 (strict).",
        "\\begin{tabularx}{\\textwidth}{@{}c c r l l c c l@{}}",
        "\\toprule",
        "Mesh & Elements & Element size $h$ & Acoustic $\\bar{\\omega}_T$ & Relative error & Step variation "
        "& Reproducibility $s_i$ & In rate fit? \\\\",
        "\\midrule"
    ]

    for i, m in enumerate(meshes):
        h_str = f"${1.0/m:.4f}$"
        el_str = f"${m} \\times {m}$"
        om_str = f"${omegas[i]:.12f}$"
        err_str = f"${rel_errs[i]:.2e}$"
        if i == 0:
            step_str = "---"
        else:
            diff = abs(omegas[i] - omegas[i-1]) / omegas[i]
            step_str = f"${diff:.2e}$"

        s_i = spreads[i]
        ratio = rel_errs[i] / max(s_i, spread_floor)
        in_fit = "yes" if ratio > F else f"no (ratio {ratio:.3g})"
        s_str = f"${s_i:.2e}$" if s_i is not None else "$<10^{-15}$"
        lines.append(f"${m}^2$ & {el_str} & {h_str} & {om_str} & {err_str} & {step_str} & {s_str} & {in_fit} \\\\")

    fitted = [str(m) for m, r in zip(meshes, [rel_errs[i] / max(spreads[i], spread_floor) for i in range(len(meshes))]) if r > F]
    excluded = [str(m) for m, r in zip(meshes, [rel_errs[i] / max(spreads[i], spread_floor) for i in range(len(meshes))]) if not r > F]
    lines.extend([
        "\\midrule",
        f"\\multicolumn{{8}}{{@{{l@{{}}}}{{\\textbf{{Closed-form exact frequency:}} $\\bar{{\\omega}}_{{T,\\mathrm{{exact}}}} = {om_exact:.12f}$}} \\\\",
        "\\multicolumn{8}{@{}l@{}}{\\textbf{Observed convergence rate (empirical least-squares, no theoretical order claimed):} "
        f"$p = {slope:.2f}$ (95\\% CI: $[{ci[0]:.2f}, {ci[1]:.2f}]$), fitted over " + ", ".join(f"${m}^2$" for m in fitted) + "}; "
        + (("the $" + excluded[0] + "^2$ level is reported as resolution-limited (excluded: relative error below $F = " + f"{F:g}" + "$ times its own reproducibility)" + ".") if excluded else "no level was excluded") + "} \\\\",
        f"\\multicolumn{{8}}{{@{{l@{{}}}}{{\\textbf{{Operational resolution floor (mesh change):}} $\\varepsilon_\\Delta = \\max(|\\omega_{{32}}-\\omega_{{16}}|/\\omega_{{32}}, \\mathrm{{err}}_{{32}}) = {eps_Delta:.2e}$"
        " --- distinct from the measurement reproducibility $s_i$}} \\\\",
        "\\bottomrule",
        "\\end{tabularx}"
    ])

    content = "\n".join(lines) + "\n"
    with open(out_tex, 'w') as f:
        f.write(content)
    print(f"Generated {out_tex}")

if __name__ == '__main__':
    main()
