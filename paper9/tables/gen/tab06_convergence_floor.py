#!/usr/bin/env python3
"""
tab06_convergence_floor.py
Generate Table 6: Mesh convergence, observed convergence order (95% CI), and resolution floor.
Data source: paper9/verification/suite/p4b_5g_to_5i.json (Test 5i).
Outputs: paper9/tables/out/tab06_convergence_floor.tex
"""
import os
import json

def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
    data_file = os.path.join(repo_root, 'paper9/verification/suite/p4b_5g_to_5i.json')
    out_dir = os.path.join(repo_root, 'paper9/tables/out')
    os.makedirs(out_dir, exist_ok=True)
    out_tex = os.path.join(out_dir, 'tab06_convergence_floor.tex')

    with open(data_file) as f:
        data = json.load(f)['5i']

    meshes = data['meshes'] # [4, 8, 16, 32]
    omegas = data['omega']
    rel_errs = data['rel_err']
    slope = data['slope']
    ci = data['CI95']
    eps_Delta = data['eps_Delta']
    om_exact = data['omega_exact']

    lines = [
        "% Auto-generated by tab06_convergence_floor.py - DO NOT EDIT MANUALLY",
        "\\begin{tabularx}{\\textwidth}{@{}c c r l l c@{}}",
        "\\toprule",
        "Mesh & Elements & Element size $h$ & Acoustic $\\bar{\\omega}_T$ & Relative error & Step variation \\\\",
        "\\midrule"
    ]

    for i, m in enumerate(meshes):
        h_str = f"${1.0/m:.4f}$"
        el_str = f"${m} \\times {m}$"
        om_str = f"${omegas[i]:.12f}$"
        err_str = f"${rel_errs[i]:.2e}$"
        if i == 0:
            step_str = "---"
        else:
            diff = abs(omegas[i] - omegas[i-1]) / omegas[i]
            step_str = f"${diff:.2e}$"

        lines.append(f"${m}^2$ & {el_str} & {h_str} & {om_str} & {err_str} & {step_str} \\\\")

    lines.extend([
        "\\midrule",
        f"\\multicolumn{{6}}{{@{{l@{{}}}}{{\\textbf{{Closed-form exact frequency:}} $\\bar{{\\omega}}_{{T,\\mathrm{{exact}}}} = {om_exact:.12f}$}} \\\\",
        f"\\multicolumn{{6}}{{@{{l@{{}}}}{{\\textbf{{Fitted convergence rate (empirical least-squares):}} $p = {slope:.2f}$ (95\\% CI: $[{ci[0]:.2f}, {ci[1]:.2f}]$; no theoretical order claimed)}} \\\\",
        f"\\multicolumn{{6}}{{@{{l@{{}}}}{{\\textbf{{Numerical resolution floor:}} $\\varepsilon_\\Delta = \\max(|\\omega_{{32}}-\\omega_{{16}}|/\\omega_{{32}}, \\mathrm{{err}}_{{32}}) = {eps_Delta:.2e}$}} \\\\",
        "\\bottomrule",
        "\\end{tabularx}"
    ])

    content = "\n".join(lines) + "\n"
    with open(out_tex, 'w') as f:
        f.write(content)
    print(f"Generated {out_tex}")

if __name__ == '__main__':
    main()
