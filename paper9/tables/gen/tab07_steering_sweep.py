#!/usr/bin/env python3
"""
tab07_steering_sweep.py
Generate Table 7: P12B steering theta-sweep on the locked S7 ring |k|=0.5:
group-velocity deviation delta_max(theta) and principal steering axis
phi*(theta) for AR in {5, 10}, plus the figure of merit M_s.
Data source: paper9/results/raw/p12b_s7_theta_sweep.json (registry-first;
never hand-edited).
Outputs: paper9/tables/out/tab07_steering_sweep.tex
"""
import os
import json


def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
    data_file = os.path.join(repo_root, 'paper9/results/raw/p12b_s7_theta_sweep.json')
    out_dir = os.path.join(repo_root, 'paper9/tables/out')
    os.makedirs(out_dir, exist_ok=True)
    out_tex = os.path.join(out_dir, 'tab07_steering_sweep.tex')

    with open(data_file) as f:
        d = json.load(f)
    sw = d['sweep']
    ms = d['M_s']

    lines = [
        "% Auto-generated by tab07_steering_sweep.py from p12b_s7_theta_sweep.json - DO NOT EDIT MANUALLY",
        "\\begin{tabularx}{\\textwidth}{@{}c r r r r@{}}",
        "\\toprule",
        "$\\theta$ & \\multicolumn{2}{c}{$\\mathrm{AR}=5$} & \\multicolumn{2}{c}{$\\mathrm{AR}=10$} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
        " & $\\delta_{\\max}$ [deg] & $\\phi^*$ [deg] & $\\delta_{\\max}$ [deg] & $\\phi^*$ [deg] \\\\",
        "\\midrule",
    ]
    for th in [0, 15, 30, 45, 60, 75, 90]:
        r5 = sw[f"AR_5_th_{th}"]
        r10 = sw[f"AR_10_th_{th}"]
        lines.append(
            f"${th}^\\circ$ & {r5['delta_max_deg']:.4f} & {r5['phi_star_deg']:.0f} "
            f"& {r10['delta_max_deg']:.4f} & {r10['phi_star_deg']:.0f} \\\\"
        )
    lines += [
        "\\midrule",
        "\\multicolumn{5}{@{}>{\\raggedright\\arraybackslash}p{\\dimexpr\\textwidth-2\\tabcolsep\\relax}@{}}{$M_s = \\phi^*(90^\\circ) - \\phi^*(0^\\circ)$: "
        f"$M_s(\\mathrm{{AR}}{{=}}5) = {ms['AR_5']['M_s_deg']:+.4f}^\\circ$, "
        f"$M_s(\\mathrm{{AR}}{{=}}10) = {ms['AR_10']['M_s_deg']:+.4f}^\\circ$ "
        "(locked grid; parabolic-refined values identical to shown precision)}\\\\",
        "\\multicolumn{5}{@{}>{\\raggedright\\arraybackslash}p{\\dimexpr\\textwidth-2\\tabcolsep\\relax}@{}}{Symmetries verified numerically ($<10^{-6}\,$deg headless / $<10^{-8}\,$deg mirror): "
        "$\\delta(\\phi;\\theta)=\\delta(\\phi+180^\\circ;\\theta)$ (headless) and "
        "$\\delta(\\phi;\\theta)=\\delta(90^\\circ-\\phi;\\,90^\\circ-\\theta)$ (mirror).}\\\\",
        "\\bottomrule",
        "\\end{tabularx}",
    ]

    with open(out_tex, 'w') as f:
        f.write("\n".join(lines) + "\n")
    print(f"Generated {out_tex}")


if __name__ == '__main__':
    main()
