#!/usr/bin/env python3
"""Table 7 (tab07_steering_sweep): orientation sweep of the steering deviation.

Regenerated from the n = 16 authoritative sweep artefact
(results/raw/p12b_s7_theta_sweep_mesh16.json).  The layout is unchanged from the
P12AH/P12AI repair; the values and the two note rows come from the n = 16 data.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

P9 = Path(__file__).resolve().parents[2]
SRC = P9 / "results" / "raw" / "p12b_s7_theta_sweep_mesh16.json"
OUT = P9 / "tables" / "out" / "tab07_steering_sweep.tex"
COLS = r"\begin{tabularx}{\textwidth}{@{}c r r r r@{}}"
NOTE = r"\multicolumn{5}{@{}>{\raggedright\arraybackslash}p{\dimexpr\textwidth-2\tabcolsep\relax}@{}}"


def sci(x: float) -> str:
    """One-significant-figure scientific notation, with the mantissa rounded UP.

    The value is printed only inside a bound (``$\\le$ sci(resid)``), so rounding the mantissa
    down would print a claim the measurement violates: the measured 1.2074e-06 deg residual
    must render as 1.3e-06, not 1.2e-06.
    """
    exp = math.floor(math.log10(x))
    mant = math.ceil(x / 10.0 ** exp * 10.0) / 10.0
    if mant >= 10.0:
        mant, exp = 1.0, exp + 1
    return f"{mant:g}\\times 10^{{{int(exp)}}}"


def main() -> None:
    d = json.loads(SRC.read_text())
    sw, ms, sc = d["sweep"], d["M_s"], d["symmetry_checks"]
    resid = max(max(v["headless_180_max_dev_deg"],
                    max(v["mirror_delta(ph;th)=delta(90-ph;90-th)_max_dev_deg"].values()))
                for v in sc.values())
    lines = [
        "% Auto-generated by tab07_steering_sweep.py from "
        "p12b_s7_theta_sweep_mesh16.json - DO NOT EDIT MANUALLY",
        COLS,
        r"\toprule",
        r"$\theta$ & \multicolumn{2}{c}{$\mathrm{AR}=5$} & \multicolumn{2}{c}{$\mathrm{AR}=10$} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r" & $\delta_{\max}$ [deg] & $\phi^*$ [deg] & $\delta_{\max}$ [deg] & $\phi^*$ [deg] \\",
        r"\midrule",
    ]
    for th in (0, 15, 30, 45, 60, 75, 90):
        r5 = sw[f"AR_5_th_{th}"]
        r10 = sw[f"AR_10_th_{th}"]
        lines.append(f"${th}^\\circ$ & {r5['delta_max_deg']:.4f} & {r5['phi_star_deg']:.0f} "
                     f"& {r10['delta_max_deg']:.4f} & {r10['phi_star_deg']:.0f} \\\\")
    lines += [
        r"\midrule",
        NOTE + "{" + r"$M_s = \phi^*(90^\circ) - \phi^*(0^\circ)$: "
        + f"$M_s(\\mathrm{{AR}}{{=}}5) = {ms['AR_5']['M_s_deg']:+.4f}^\\circ$, "
        + f"$M_s(\\mathrm{{AR}}{{=}}10) = {ms['AR_10']['M_s_deg']:+.4f}^\\circ$ "
        # The parabolic refinement of the peak is quoted only qualitatively: its value is not
        # resolved by the locked 5 deg sweep (the peak top is flat to within a sampling step, and
        # the refinement is unstable across the n = 8 / n = 16 meshes), so no refined digit is
        # printed here.  The peak position itself is resolved to the 5 deg grid, which is what the
        # M_s figure states.
        + "(locked $5^\\circ$ grid; parabolic refinement of the peak lies within one sampling step "
        + "of these figures, so the sweep does not resolve any finer value)" + "}\\\\",
        NOTE + "{" + f"Symmetries verified numerically ($\\le {sci(resid)}\\,$deg for both headless and mirror): "
        + r"$\delta(\phi;\theta)=\delta(\phi+180^\circ;\theta)$ (headless) and "
        + r"$\delta(\phi;\theta)=\delta(90^\circ-\phi;\,90^\circ-\theta)$ (mirror)." + "}\\\\",
        r"\bottomrule",
        r"\end{tabularx}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Generated {OUT}")
    print(f"symmetry residual max = {resid:.6e} deg -> {sci(resid)}")


if __name__ == "__main__":
    main()
